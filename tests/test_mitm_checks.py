def test_profiles_are_read_through_nmcli_with_escaped_values():
    calls = []

    def runner(args, **kwargs):
        calls.append(args)
        if args[-2:] == ['connection', 'show']:
            return SimpleNamespace(returncode=0, stdout='u1\nu2\n')
        uuid = args[-1]
        return SimpleNamespace(returncode=0, stdout=f'connection.id:Ev\\: {uuid}\nconnection.uuid:{uuid}\n'
                                                    'ipv6.dns:2620\\:119\\:35\\:\\:35\n')
    read = profiles.read_profiles(runner)
    assert [p['connection.id'] for p in read] == ['Ev: u1', 'Ev: u2']
    assert read[0]['ipv6.dns'] == '2620:119:35::35'
    assert all('--show-secrets' not in call and '-s' not in call for call in calls)
    assert profiles.read_profiles(lambda *a, **k: SimpleNamespace(returncode=8, stdout='')) is None


