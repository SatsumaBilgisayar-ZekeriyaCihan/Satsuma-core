def fake_proc(tmp_path, values, interfaces=('all', 'default', 'lo', 'wlp2s0')):
    root = tmp_path / 'sys'
    for key, value in {**kernel_settings.expected(str(root), lambda p: list(interfaces)), **values}.items():
        path = root / key
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(values.get(key, kernel_settings.expected(str(root), lambda p: list(interfaces))[key]) + '\n')
    return str(root)


def test_route_localnet_on_any_single_interface_is_drift(tmp_path):
    root = fake_proc(tmp_path, {'net/ipv4/conf/wlp2s0/route_localnet': '1'})
    assert kernel_settings.drift(root) == [
        {'key': 'net/ipv4/conf/wlp2s0/route_localnet', 'expected': '0', 'actual': '1'}]


def test_clean_settings_have_no_drift(tmp_path):
    assert kernel_settings.drift(fake_proc(tmp_path, {})) == []


def test_restores_only_drifted_keys_to_hardened_values(tmp_path):
    root = fake_proc(tmp_path, {'net/ipv4/conf/wlp2s0/route_localnet': '1', 'net/ipv4/conf/all/rp_filter': '0'})
    result = kernel_settings.restore(root)
    assert sorted(i['key'] for i in result['restored']) == ['net/ipv4/conf/all/rp_filter',
                                                           'net/ipv4/conf/wlp2s0/route_localnet']
    assert kernel_settings.drift(root) == [] and result['failed'] == []


def test_refuses_to_follow_symlinks_when_restoring(tmp_path):
    root = fake_proc(tmp_path, {})
    target = tmp_path / 'elsewhere'
    target.write_text('0\n')  # drifted value behind a link
    key = os.path.join(root, 'net/ipv4/conf/all/rp_filter')
    os.unlink(key)
    os.symlink(target, key)
    result = kernel_settings.restore(root)
    assert result['restored'] == [] and result['failed'][0]['key'] == 'net/ipv4/conf/all/rp_filter'
    assert target.read_text() == '0\n'


OWN = {ipaddress.ip_address('192.168.1.10')}


def route(**fields):
    return {key: fields.get(key) for key in routes._KEEP}


CLEAN = {'routes': [route(dst='default', gateway='192.168.1.1', dev='wlp2s0'),
                    route(type='local', dst='127.0.0.0/8', dev='lo', table='local'),
                    route(type='broadcast', dst='127.255.255.255', dev='lo', table='local'),
                    route(type='local', dst='192.168.1.10', dev='wlp2s0', table='local'),
                    route(type='local', dst='::1', dev='lo', table='local')],
         'rules': [{'table': 'local'}, {'table': 'main'}, {'table': 'default'}]}


def test_normal_tables_including_loopback_broadcast_are_clean():
    assert routes.inspect(CLEAN, OWN) == []


@pytest.mark.parametrize('extra,code', [
    (route(type='broadcast', dst='127.255.255.255', dev='wlp2s0', table='local'), 'loopback_route_off_lo'),
    (route(dst='127.0.0.0/8', dev='eth0'), 'loopback_route_off_lo'),
    (route(dst='::1', dev='eth0'), 'loopback_route_off_lo'),
    (route(type='local', dst='8.8.8.8', dev='lo', table='local'), 'local_route_for_foreign_address'),
    (route(type='local', dst='192.168.1.0/24', dev='lo', table='local'), 'local_route_for_foreign_address'),
])
def test_loopback_and_interception_routes_are_critical(extra, code):
    snap = {**CLEAN, 'routes': CLEAN['routes'] + [extra]}
    assert [f['code'] for f in routes.inspect(snap, OWN)] == [code]


@pytest.mark.parametrize('extra,resolvers', [
    (route(dst='8.8.8.8', gateway='192.168.1.66', dev='wlp2s0'), ['8.8.8.8']),
    (route(dst='1.1.1.0/24', dev='wlp2s0', scope='link'), ['1.1.1.1']),        # answered on the LAN
    (route(dst='9.9.9.9', gateway='10.8.0.1', dev='tun0', table='100'), ['9.9.9.9']),
    (route(dst='2001:4860:4860::8888', gateway='fe80::66', dev='wlp2s0'), ['2001:4860:4860::8888']),
    (route(dst='208.67.222.222', gateway='192.168.1.66', dev='wlp2s0'), ['208.67.222.222'])])
def test_a_route_that_redirects_a_public_resolver_is_critical(extra, resolvers):
    snap = {**CLEAN, 'routes': CLEAN['routes'] + [extra]}
    [finding] = routes.inspect(snap, OWN)
    assert (finding['code'], finding['severity'], finding['resolvers']) == ('dns_resolver_route', 'critical', resolvers)


def test_pinned_servers_are_watched_too_and_broad_vpn_routes_are_not():
    pinned = ipaddress.ip_address('195.175.39.39')
    snap = {**CLEAN, 'routes': CLEAN['routes'] + [route(dst='195.175.39.39', gateway='192.168.1.66', dev='wlp2s0'),
                                                  route(dst='0.0.0.0/1', gateway='10.8.0.1', dev='tun0'),
                                                  route(dst='128.0.0.0/1', gateway='10.8.0.1', dev='tun0')]}
    assert routes.inspect(snap, OWN) == []
    assert [f['resolvers'] for f in routes.inspect(snap, OWN, {pinned})] == [['195.175.39.39']]


def test_a_blackholed_resolver_is_only_information():
    snap = {**CLEAN, 'routes': CLEAN['routes'] + [route(type='blackhole', dst='8.8.8.8')]}
    assert [(f['code'], f['severity']) for f in routes.inspect(snap, OWN)] == [('dns_resolver_blocked', 'info')]


def test_extra_policy_rule_is_reported():
    snap = {**CLEAN, 'rules': CLEAN['rules'] + [{'priority': 100, 'table': '100'}]}
    assert [f['code'] for f in routes.inspect(snap, OWN)] == ['extra_policy_rule']


def test_default_route_change_is_an_event():
    moved = {**CLEAN, 'routes': [route(dst='default', gateway='192.168.1.66', dev='wlp2s0')] + CLEAN['routes'][1:]}
    assert routes.changes(None, CLEAN) == [] and routes.changes(CLEAN, CLEAN) == []
    assert routes.changes(CLEAN, moved)[0]['code'] == 'default_route_changed'


def test_snapshot_survives_a_disabled_address_family():
    def runner(args, **kwargs):
        if '-6' in args:
            return SimpleNamespace(returncode=255, stdout='', stderr='Address family not supported')
        return SimpleNamespace(returncode=0, stdout='[{"dst": "default", "dev": "eth0"}]' if 'route' in args else '[]')
    snap = routes.snapshot(runner)
    assert snap['routes'][0]['dst'] == 'default' and len(snap['unavailable']) == 2


