IP = ipaddress.ip_address


NM_OUTPUT = 'IP4.DNS[1]:195.175.39.39\nIP6.DNS[1]:2001\\:db8\\:\\:53\nIP4.DNS[2]:\n'


def resolv(tmp_path, text, name='resolv.conf'):
    path = tmp_path / name
    path.write_text(text)
    return str(path)


def check(path, known, uid=0, **kwargs):
    """dns.findings with the file's owner set to `uid` (tests do not run as root)."""
    def stat_file(p):
        info = os.stat(p)
        return os.stat_result((info.st_mode, *info[1:4], uid, *info[5:]))
    kwargs.setdefault('is_immutable', lambda p: False)
    kwargs.setdefault('pinned', frozenset)
    return dns.findings(path=path, known=lambda: known, stat_file=stat_file, **kwargs)


def test_networkmanager_servers_are_parsed_from_nmcli():
    runner = lambda *a, **k: SimpleNamespace(returncode=0, stdout=NM_OUTPUT)
    assert dns.networkmanager_servers(runner) == {IP('195.175.39.39'), IP('2001:db8::53')}
    assert dns.networkmanager_servers(lambda *a, **k: SimpleNamespace(returncode=8, stdout='')) is None


def test_servers_networkmanager_configured_are_clean(tmp_path):
    path = resolv(tmp_path, '# Generated by NetworkManager\nnameserver 195.175.39.39\n')
    os.chmod(path, 0o644)
    assert check(path, {IP('195.175.39.39')}) == []


def test_a_server_written_into_the_file_directly_is_reported(tmp_path):
    path = resolv(tmp_path, 'nameserver 195.175.39.39\nnameserver 203.0.113.66\n')
    os.chmod(path, 0o644)
    assert check(path, {IP('195.175.39.39')}) == [
        {'code': 'dns_server_not_from_networkmanager', 'severity': 'high', 'server': '203.0.113.66'}]


def test_without_networkmanager_servers_are_not_judged(tmp_path):
    path = resolv(tmp_path, 'nameserver 203.0.113.66\n')
    os.chmod(path, 0o644)
    assert check(path, None) == []


def test_behind_the_resolved_stub_the_upstreams_are_checked(tmp_path):
    path = resolv(tmp_path, 'nameserver 127.0.0.53\noptions edns0\n')
    os.chmod(path, 0o644)
    upstreams = resolv(tmp_path, 'nameserver 203.0.113.66\n', 'upstreams.conf')
    [finding] = check(path, {IP('195.175.39.39')}, upstreams=upstreams)
    assert finding['server'] == '203.0.113.66'


def test_a_file_others_can_write_or_not_owned_by_root_is_critical(tmp_path):
    path = resolv(tmp_path, 'nameserver 195.175.39.39\n')
    os.chmod(path, 0o666)
    assert [f['code'] for f in check(path, {IP('195.175.39.39')})] == ['resolv_conf_writable']
    os.chmod(path, 0o644)
    assert [f['code'] for f in check(path, {IP('195.175.39.39')}, uid=1000)] == ['resolv_conf_writable']


def test_a_link_outside_the_managed_files_is_reported(tmp_path):
    target = resolv(tmp_path, 'nameserver 195.175.39.39\n', 'evil.conf')
    os.chmod(target, 0o644)
    link = tmp_path / 'resolv.conf'
    os.symlink(target, link)
    findings = check(str(link), {IP('195.175.39.39')})
    assert [f['code'] for f in findings] == ['resolv_conf_unexpected_link']
    assert check(str(link), {IP('195.175.39.39')}, allowed_targets=(target,)) == []


def test_immutable_file_is_reported_with_what_it_breaks(tmp_path):
    path = resolv(tmp_path, 'nameserver 195.175.39.39\n')
    os.chmod(path, 0o644)
    assert [f['code'] for f in check(path, None, is_immutable=lambda p: True)] == ['resolv_conf_immutable']


def test_immutable_check_tolerates_filesystems_without_attributes(tmp_path):
    assert dns.immutable(resolv(tmp_path, '')) is False
    assert dns.immutable(str(tmp_path / 'missing')) is False


def test_pinned_servers_judge_the_filter_upstream_not_what_dhcp_hands_out(tmp_path):
    path = resolv(tmp_path, 'nameserver 192.168.1.1\n')
    os.chmod(path, 0o644)
    opendns = lambda: {IP('208.67.222.222'), IP('208.67.220.220')}
    # Port 53 is redirected to the filter: the modem's DNS from DHCP is fine.
    assert check(path, {IP('192.168.1.1')}, pinned=opendns, upstream='208.67.222.222') == []
    assert check(path, {IP('192.168.1.1')}, pinned=opendns, upstream='192.168.1.1') == [
        {'code': 'dns_upstream_not_pinned', 'severity': 'high', 'server': '192.168.1.1'}]
    # A server written into resolv.conf by hand is still reported.
    assert [f['code'] for f in check(path, set(), pinned=opendns, upstream='208.67.222.222')] == [
        'dns_server_not_from_networkmanager']


