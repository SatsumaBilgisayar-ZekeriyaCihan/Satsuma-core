def codes(profile, pinned=OPENDNS):
    return [(f['code'], f['severity']) for f in profiles.audit(profile, pinned)]


def test_a_profile_pinned_to_opendns_is_only_inventoried():
    assert codes(WIRED) == [('network_profile', 'info')]


def test_proxy_vpn_and_foreign_dns_are_reported():
    assert ('network_profile_proxy', 'high') in codes({**WIRED, 'proxy.method': 'auto',
                                                      'proxy.pac-url': 'http://192.168.1.66/wpad.dat'})
