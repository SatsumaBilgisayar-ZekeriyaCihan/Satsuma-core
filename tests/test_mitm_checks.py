def sockets():
    return procnet.parse(TCP4, 'tcp', 4) + procnet.parse(UDP4, 'udp', 4)


def test_exposed_listeners_skip_loopback_and_client_sockets():
    identities = {100: {'pid': 1, 'exe': '/usr/sbin/sshd', 'comm': 'sshd'}}
    found = procnet.exposed_listeners(read=sockets, owner_lookup=lambda inodes: identities)
    assert [(l['proto'], l['address'], l['port']) for l in found] == [
        ('tcp', '0.0.0.0', 22), ('tcp', '192.168.1.10', 5900), ('udp', '0.0.0.0', 5353)]
    assert found[0]['process']['exe'] == '/usr/sbin/sshd' and found[1]['process'] is None


def listener(port, exe=None, comm=None, suspicious=False, proto='tcp'):
    process = {'pid': 5, 'exe': exe, 'comm': comm} if exe or comm else None
    return {'proto': proto, 'address': '0.0.0.0', 'port': port, 'uid': 0, 'process': process,
            'suspicious': suspicious}


@pytest.mark.parametrize('item,service', [
    (listener(2222, '/usr/sbin/sshd'), 'ssh'),
    (listener(3389, '/usr/libexec/gnome-remote-desktop-daemon'), 'rdp'),
    (listener(445, '/usr/sbin/smbd (deleted)'), 'smb'),
    (listener(5938, comm='teamviewerd'), 'teamviewer'),
    (listener(7070, '/usr/libexec/anydesk/anydesk', 'anydesk'), 'anydesk'),
    (listener(21116, '/opt/rustdesk/rustdesk', proto='udp'), 'rustdesk'),
    (listener(2049), 'nfs'),        # kernel NFS server: no owning process, known port
    (listener(5901), 'vnc'),
    (listener(22, '/usr/bin/python3'), None),  # a named program is not judged by its port
    (listener(5353, '/usr/sbin/avahi-daemon', proto='udp'), None)])
def test_remote_access_servers_are_recognised(item, service):
    assert remote_access.service_of(item) == service


